namespace Riwaq.Application.Abstractions;

public sealed record PdfValidationResult(bool IsValid, string? ErrorCode, int PageCount, bool IsEncrypted);

public sealed record ExtractedLine(string Text, double FontSize, double Top, bool IsBold);

public sealed record ExtractedPage(
    int Number,
    string Text,
    IReadOnlyList<ExtractedLine> Lines,
    int LetterCount,
    int ImageCount,
    double Width,
    double Height,
    // Most of the text is invisible: an OCR layer laid over a scanned image by another tool, often poor quality.
    bool HasInvisibleTextLayer = false);

public sealed record OutlineEntry(string Title, int PageNumber, int Level);

public sealed record ExtractedDocument(int PageCount, IReadOnlyList<ExtractedPage> Pages, IReadOnlyList<OutlineEntry> Outline);

public interface IPdfExtractor
{
    PdfValidationResult Validate(string filePath);
    ExtractedDocument Extract(string filePath, CancellationToken cancellationToken);
}

public sealed record OcrResult(bool Success, string Text, double? MeanConfidence, string? ErrorCode);

public interface IOcrEngine
{
    bool IsAvailable { get; }

    /// <summary>"ai-vision", "tesseract" or "none".</summary>
    string Name { get; }
    Task<OcrResult> RecognizePageAsync(string pdfPath, int pageNumber, string languages, CancellationToken cancellationToken);

    /// <summary>Reads a photo (JPEG produced by <see cref="IImageProcessor"/>).</summary>
    Task<OcrResult> RecognizeImageAsync(byte[] jpeg, string languages, CancellationToken cancellationToken);
}

/// <summary>A photo decoded, turned upright (EXIF orientation), scaled down and re-encoded as JPEG.</summary>
public sealed record NormalizedImage(byte[] Jpeg, int Width, int Height);

public interface IImageProcessor
{
    /// <summary>Returns null when the data is not a supported image (JPEG, PNG, WebP, GIF, BMP, HEIC where the platform decodes it).</summary>
    NormalizedImage? Normalize(byte[] data);
}

public sealed record VideoCaption(double StartSeconds, double DurationSeconds, string Text);

public sealed record VideoDetails(string VideoId, string Title, string Author, int DurationSeconds);

public sealed record VideoTranscript(string Language, bool IsAutoGenerated, IReadOnlyList<VideoCaption> Captions);

/// <summary>Reads public YouTube video metadata and captions.</summary>
public interface IVideoTranscriptSource
{
    /// <summary>Throws <see cref="Common.ValidationException"/> ("video_unavailable") when the video cannot be read.</summary>
    Task<VideoDetails> GetDetailsAsync(string videoId, CancellationToken cancellationToken);

    /// <summary>Best caption track for the language (manual before auto-generated); null when the video has no captions.</summary>
    Task<VideoTranscript?> GetTranscriptAsync(string videoId, string preferredLanguage, CancellationToken cancellationToken);
}

public interface IFileStorage
{
    Task SaveAsync(string key, Stream content, CancellationToken cancellationToken);
    Task<Stream> OpenReadAsync(string key, CancellationToken cancellationToken);
    Task DeleteAsync(string key, CancellationToken cancellationToken);
    Task<bool> ExistsAsync(string key, CancellationToken cancellationToken);

    /// <summary>A local path for libraries that need one (PDF parsing, OCR). Downloads to a temp file for remote stores.</summary>
    Task<string> GetLocalPathAsync(string key, CancellationToken cancellationToken);
}

/// <summary>Wakes the background worker when a new processing job is queued.</summary>
public interface IProcessingSignal
{
    void Notify();
    Task WaitAsync(TimeSpan timeout, CancellationToken cancellationToken);
}

/// <summary>Pushes real-time updates to a user's connected clients (SignalR).</summary>
public interface IRealtimeNotifier
{
    Task SendToUserAsync(Guid userId, string eventName, object payload, CancellationToken cancellationToken = default);
}
