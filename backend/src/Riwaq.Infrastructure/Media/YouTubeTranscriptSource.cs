using Microsoft.Extensions.Logging;
using Riwaq.Application.Abstractions;
using Riwaq.Application.Common;
using YoutubeExplode;
using YoutubeExplode.Exceptions;
using YoutubeExplode.Videos.ClosedCaptions;

namespace Riwaq.Infrastructure.Media;

/// <summary>Public video metadata and captions through YoutubeExplode (no API key; only public videos).</summary>
public sealed class YouTubeTranscriptSource(HttpClient http, ILogger<YouTubeTranscriptSource> logger) : IVideoTranscriptSource
{
    private readonly YoutubeClient _youtube = new(http);

    public async Task<VideoDetails> GetDetailsAsync(string videoId, CancellationToken cancellationToken)
    {
        try
        {
            var video = await _youtube.Videos.GetAsync(videoId, cancellationToken);
            return new VideoDetails(videoId, video.Title, video.Author.ChannelTitle, (int)(video.Duration?.TotalSeconds ?? 0));
        }
        catch (Exception ex) when (ex is YoutubeExplodeException or HttpRequestException)
        {
            logger.LogWarning("YouTube video {VideoId} could not be read: {Error}", videoId, ex.GetType().Name);
            throw new ValidationException("video_unavailable", "This video is private, removed or cannot be read.");
        }
    }

    public async Task<VideoTranscript?> GetTranscriptAsync(string videoId, string preferredLanguage, CancellationToken cancellationToken)
    {
        try
        {
            var manifest = await _youtube.Videos.ClosedCaptions.GetManifestAsync(videoId, cancellationToken);
            var track = PickTrack(manifest.Tracks, preferredLanguage);
            if (track is null) return null;

            var captions = await _youtube.Videos.ClosedCaptions.GetAsync(track, cancellationToken);
            var lines = captions.Captions
                .Where(c => !string.IsNullOrWhiteSpace(c.Text))
                .Select(c => new VideoCaption(c.Offset.TotalSeconds, c.Duration.TotalSeconds, c.Text))
                .ToList();
            return new VideoTranscript(Language(track), track.IsAutoGenerated, lines);
        }
        catch (Exception ex) when (ex is YoutubeExplodeException or HttpRequestException)
        {
            logger.LogWarning("Captions of {VideoId} could not be read: {Error}", videoId, ex.GetType().Name);
            throw new ValidationException("video_unavailable", "The captions of this video could not be read.");
        }
    }

    /// <summary>Preferred language first (manual before auto-generated), then any manual track, then any auto track.</summary>
    internal static ClosedCaptionTrackInfo? PickTrack(IReadOnlyList<ClosedCaptionTrackInfo> tracks, string preferredLanguage) =>
        tracks.OrderBy(t => Language(t) == preferredLanguage ? 0 : 1)
            .ThenBy(t => t.IsAutoGenerated ? 1 : 0)
            .FirstOrDefault();

    private static string Language(ClosedCaptionTrackInfo track) =>
        track.Language.Code.Split('-', '_')[0].ToLowerInvariant();
}
